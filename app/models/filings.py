"""Statutory return filing: challans, filing records, generated artefacts.

A report that looks right and a file a government portal accepts are different
artefacts, and only the second one is worth anything on a filing deadline. What
is modelled here is the second kind, plus the paper trail an inspection asks
for afterwards.

Two things justify their own tables:

- **TDS challans.** A 24Q return cannot be filed at all without mapping every
  deduction line to the challan it was deposited under — BSR code, deposit date,
  challan serial. That mapping is a fact about a bank payment, not something
  derivable from payroll, so it has to be recorded.
- **Filing records.** The acknowledgement number comes back from the portal and
  is typed in by an HR user afterwards. Nothing in the system can compute it,
  and it is the first thing an inspector asks for.
"""

from __future__ import annotations

import enum
import uuid
from datetime import date, datetime

from sqlalchemy import (
    Boolean,
    Date,
    DateTime,
    Enum,
    ForeignKey,
    Integer,
    Numeric,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.dialects.postgresql import UUID as PgUUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base, TenantMixin, TimestampMixin, UUIDMixin


class ReturnType(str, enum.Enum):
    PF_ECR = "pf_ecr"
    ESIC = "esic"
    PROFESSIONAL_TAX = "professional_tax"
    TDS_24Q = "tds_24q"


class FilingStatus(str, enum.Enum):
    # Validation found defects; no file exists.
    BLOCKED = "blocked"
    GENERATED = "generated"
    # Uploaded to the portal and acknowledged.
    FILED = "filed"
    # The portal rejected it. `rejection_reason` says why, so the next attempt
    # has something to work from.
    REJECTED = "rejected"


class FilingRecord(Base, UUIDMixin, TenantMixin, TimestampMixin):
    """One generated return, and what happened to it.

    Rows accumulate: a regenerated return is a new row, not an edit of the old
    one. A filing history that quietly rewrites itself is not a filing history,
    and "which file did we actually upload in July" is exactly the question an
    inspection asks.
    """

    __tablename__ = "filing_records"

    return_type: Mapped[ReturnType] = mapped_column(
        Enum(ReturnType, name="return_type"), nullable=False, index=True
    )
    legal_entity_id: Mapped[uuid.UUID] = mapped_column(
        PgUUID(as_uuid=True), ForeignKey("legal_entities.id", ondelete="RESTRICT"), nullable=False
    )

    # "2026-04" for a monthly return, "2026-2027-Q1" for a quarterly one.
    # A string because the shape genuinely differs by return type, and parsing
    # it is never needed — it is an identifier, not a date.
    period: Mapped[str] = mapped_column(String(32), nullable=False, index=True)
    # State code for Professional Tax, which is filed per state. Null for
    # central returns.
    jurisdiction: Mapped[str | None] = mapped_column(String(8), nullable=True, index=True)

    status: Mapped[FilingStatus] = mapped_column(
        Enum(FilingStatus, name="filing_status"), nullable=False, index=True
    )

    file_storage_key: Mapped[str | None] = mapped_column(String(512), nullable=True)
    file_name: Mapped[str | None] = mapped_column(String(255), nullable=True)
    # SHA-256 of the generated bytes. What proves the file held later is the
    # file uploaded then.
    content_hash: Mapped[str | None] = mapped_column(String(64), nullable=True)
    record_count: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    total_amount: Mapped[float] = mapped_column(Numeric(16, 2), default=0, nullable=False)

    generated_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    generated_by_user_id: Mapped[uuid.UUID | None] = mapped_column(
        PgUUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"), nullable=True
    )

    # Typed in by an HR user after the portal accepts the upload. Nothing here
    # can compute it.
    acknowledgement_number: Mapped[str | None] = mapped_column(String(64), nullable=True)
    filed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    filed_by_user_id: Mapped[uuid.UUID | None] = mapped_column(
        PgUUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"), nullable=True
    )
    rejection_reason: Mapped[str | None] = mapped_column(Text, nullable=True)

    # The exceptions found by the pre-generation validation pass. Kept on a
    # BLOCKED record so the fix list survives a page refresh, and on a
    # GENERATED one so warnings that did not block are still visible.
    validation_exceptions: Mapped[list] = mapped_column(JSONB, default=list, nullable=False)

    notes: Mapped[str | None] = mapped_column(Text, nullable=True)


class TdsChallan(Base, UUIDMixin, TenantMixin, TimestampMixin):
    """A TDS deposit made to the government.

    The BSR code, deposit date and challan serial together identify the payment
    in the tax department's own records. A 24Q whose deduction lines do not tie
    to real challans is rejected outright, so this is not optional detail.
    """

    __tablename__ = "tds_challans"
    __table_args__ = (
        UniqueConstraint(
            "tenant_id", "bsr_code", "deposit_date", "challan_serial",
            name="uq_tds_challan_identity",
        ),
    )

    legal_entity_id: Mapped[uuid.UUID] = mapped_column(
        PgUUID(as_uuid=True), ForeignKey("legal_entities.id", ondelete="RESTRICT"), nullable=False
    )

    # Seven digits identifying the collecting bank branch.
    bsr_code: Mapped[str] = mapped_column(String(7), nullable=False)
    deposit_date: Mapped[date] = mapped_column(Date, nullable=False, index=True)
    challan_serial: Mapped[str] = mapped_column(String(9), nullable=False)

    financial_year: Mapped[str] = mapped_column(String(9), nullable=False, index=True)
    quarter: Mapped[int] = mapped_column(Integer, nullable=False, index=True)

    # The components are separate because the return reports them separately,
    # and because a challan whose parts do not sum to its total is a data-entry
    # error worth catching before the portal catches it.
    tds_amount: Mapped[float] = mapped_column(Numeric(14, 2), default=0, nullable=False)
    surcharge: Mapped[float] = mapped_column(Numeric(14, 2), default=0, nullable=False)
    education_cess: Mapped[float] = mapped_column(Numeric(14, 2), default=0, nullable=False)
    interest: Mapped[float] = mapped_column(Numeric(14, 2), default=0, nullable=False)
    late_fee: Mapped[float] = mapped_column(Numeric(14, 2), default=0, nullable=False)
    total_amount: Mapped[float] = mapped_column(Numeric(14, 2), nullable=False)

    # A book-entry challan is a government deductor's transfer voucher rather
    # than a bank payment; the return reports it differently.
    is_book_entry: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)

    mappings: Mapped[list[TdsChallanMapping]] = relationship(
        back_populates="challan", cascade="all, delete-orphan"
    )

    @property
    def mapped_total(self) -> float:
        return sum((m.tds_amount for m in self.mappings), start=0)


class TdsChallanMapping(Base, UUIDMixin, TenantMixin, TimestampMixin):
    """Which employee's deduction was deposited under which challan.

    One row per employee per payslip per challan. Annexure I of the 24Q is
    essentially this table, so an unmapped deduction is a return that cannot be
    filed — which is why generation refuses rather than producing a file the
    portal will reject a week later.
    """

    __tablename__ = "tds_challan_mappings"
    __table_args__ = (
        UniqueConstraint("tenant_id", "challan_id", "payslip_id", name="uq_challan_payslip"),
    )

    challan_id: Mapped[uuid.UUID] = mapped_column(
        PgUUID(as_uuid=True), ForeignKey("tds_challans.id", ondelete="CASCADE"), nullable=False
    )
    employee_id: Mapped[uuid.UUID] = mapped_column(
        PgUUID(as_uuid=True), ForeignKey("employees.id", ondelete="CASCADE"), nullable=False
    )
    payslip_id: Mapped[uuid.UUID] = mapped_column(
        PgUUID(as_uuid=True), ForeignKey("payslips.id", ondelete="CASCADE"), nullable=False
    )

    tds_amount: Mapped[float] = mapped_column(Numeric(14, 2), nullable=False)
    # The date the deduction itself was made, which is not the deposit date and
    # is reported separately.
    deduction_date: Mapped[date] = mapped_column(Date, nullable=False)

    challan: Mapped[TdsChallan] = relationship(back_populates="mappings")
