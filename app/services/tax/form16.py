ZERO = Decimal(0)
RUPEE = Decimal("0.01")
_CLOSED = (PayrollRunStatus.APPROVED, PayrollRunStatus.PAID)

#: Deduction lines the projection reports that belong under section 16 of the
#: form, not Chapter VI-A.
_SECTION_16 = {"Standard deduction": "standard_deduction", "PT": "professional_tax"}
#: Other-income codes by the head of section 17 they fall under.
_PERQUISITE_CODES = frozenset({"LOAN_PERQUISITE"})
_PROFITS_IN_LIEU_CODES = frozenset({"GRATUITY_TAXABLE"})


class Form16UnavailableError(Exception):
    """Part B cannot honestly be produced for this year yet, and why."""


def _d(value: Any) -> Decimal:
    return Decimal(str(value)) if value not in (None, "") else ZERO


def _money(value: Decimal) -> Decimal:
    return value.quantize(RUPEE, rounding=ROUND_HALF_UP)


# ── Pure aggregation ────────────────────────────────────────────────────────


@dataclass(frozen=True, slots=True)
class SlipFacts:
    """What Part B reads off one approved payslip."""

    period_year: int
    period_month: int
    gross_earnings: Decimal
    pf_wage_base: Decimal
    professional_tax: Decimal
    tds: Decimal
    line_items: list[dict[str, Any]] = field(default_factory=list)
    input_lines: list[dict[str, Any]] = field(default_factory=list)
    tds_working: dict[str, Any] | None = None


@dataclass(frozen=True, slots=True)
class YearPay:
    months: int
    first_period: tuple[int, int]
    last_period: tuple[int, int]
    #: Taxable structure pay plus taxable one-off cash (bonus, arrears, encashment).
    salary: Decimal
    #: Non-cash taxable value paid through payroll (reward perquisites).
    perquisites: Decimal
    basic_plus_da: Decimal
    hra: Decimal
    employer_nps: Decimal
    professional_tax: Decimal
    tds_deducted: Decimal


def aggregate_year_pay(slips: list[SlipFacts]) -> YearPay:
    """Sum a financial year's approved payslips. Pure.

    Taxable structure pay is what each month's TDS working recorded as taxable
    this month; a payslip from before TDS was wired in falls back to its gross,
    the same fallback the run's own year-to-date uses.
    """
    if not slips:
        raise ValueError("No payslips to aggregate")
    salary = perquisites = basic = hra = nps = pt = tds = ZERO
    periods = sorted({(s.period_year, s.period_month) for s in slips})
    for slip in slips:
        projection = (slip.tds_working or {}).get("projection") or {}
        if "this_month_taxable_pay" in projection:
            salary += _d(projection["this_month_taxable_pay"])
        else:
            salary += _d(slip.gross_earnings)
        basic += _d(slip.pf_wage_base)
        pt += _d(slip.professional_tax)
        tds += _d(slip.tds)
        for line in slip.line_items:
            code = str(line.get("code", ""))
            if code == "HRA":
                hra += _d(line.get("amount"))
            elif code in ("NPS_ER", "EMPLOYER_NPS"):
                nps += _d(line.get("amount"))
        for line in slip.input_lines:
            if line.get("skipped"):
                continue
            taxable = _d(line.get("taxable_amount"))
            if line.get("kind") == "perquisite":
                perquisites += taxable
            else:
                salary += taxable
    return YearPay(
        months=len(periods),
        first_period=periods[0],
        last_period=periods[-1],
        salary=_money(salary),
        perquisites=_money(perquisites),
        basic_plus_da=_money(basic),
        hra=_money(hra),
        employer_nps=_money(nps),
        professional_tax=_money(pt),
        tds_deducted=_money(tds),
    )


def year_projection_input(base: ProjectionInput, pay: YearPay) -> ProjectionInput:
    """The year's actual pay, in place of the projection's salary fields. Pure.

    Income that payroll paid as input lines is already in `pay`, so it comes
    out of the base's other income rather than being counted twice.
    """
    return replace(
        base,
        gross_salary=pay.salary + pay.perquisites,
        basic_plus_da=pay.basic_plus_da,
        hra_received=pay.hra,
        employer_nps=pay.employer_nps,
        professional_tax=pay.professional_tax,
        other_income=tuple(
            line for line in base.other_income if line[0] not in PAID_THROUGH_PAYROLL
        ),
        pending_if_unclaimed=(),
    )


def part_b(
    *, pay: YearPay, inputs: ProjectionInput, computation: TaxComputation
) -> dict[str, Any]:
    """The Part B lines, in the form's order, and the TDS reconciliation. Pure.

    Checks its own arithmetic: income chargeable less Chapter VI-A must be the
    projection's taxable income, or nothing is returned.
    """
    other = {line[0]: _d(line[2]) for line in inputs.other_income}
    other_labels = {line[0]: line[1] for line in inputs.other_income}
    perquisites = pay.perquisites + sum(
        (amount for code, amount in other.items() if code in _PERQUISITE_CODES), start=ZERO
    )
    profits_in_lieu = sum(
        (amount for code, amount in other.items() if code in _PROFITS_IN_LIEU_CODES), start=ZERO
    )
    salary_17_1 = pay.salary + sum(
        (
            amount
            for code, amount in other.items()
            if code not in _PERQUISITE_CODES and code not in _PROFITS_IN_LIEU_CODES
        ),
        start=ZERO,
    )
    total_current = salary_17_1 + perquisites + profits_in_lieu
    previous_reported = inputs.previous_gross - inputs.previous_exempt
    current_exempt = _d(computation.total_exemptions) - inputs.previous_exempt
    salary_after_exemptions = total_current - current_exempt

    section_16 = {"standard_deduction": ZERO, "professional_tax": ZERO}
    chapter_via: list[dict[str, str]] = []
    for line in computation.deduction_lines:
        allowed = _d(line.allowed)
        if line.section in _SECTION_16:
            section_16[_SECTION_16[line.section]] += allowed
        elif allowed > ZERO:
            chapter_via.append(
                {
                    "section": line.section,
                    "gross": str(_money(_d(line.accepted))),
                    "deductible": str(_money(allowed)),
                }
            )
    total_16 = section_16["standard_deduction"] + section_16["professional_tax"]
    chargeable = salary_after_exemptions + previous_reported - total_16
    via_total = sum((_d(row["deductible"]) for row in chapter_via), start=ZERO)
    taxable = max(ZERO, chargeable - via_total)
    if _money(taxable) != _money(_d(computation.taxable_income)):
        raise TaxRuleError(
            f"Part B does not reconcile: income chargeable {chargeable} less deductions "
            f"{via_total} is {taxable}, but the computation's taxable income is "
            f"{computation.taxable_income}."
        )

    tax_payable = _d(computation.annual_tax_liability)
    deducted = pay.tds_deducted + inputs.previous_tds
    balance = tax_payable - deducted

    def row(key: str, label: str, amount: Decimal) -> dict[str, str]:
        return {"key": key, "label": label, "amount": str(_money(amount))}

    lines = [
        row("1a", "Salary as per provisions contained in section 17(1)", salary_17_1),
        row("1b", "Value of perquisites under section 17(2)", perquisites),
        row("1c", "Profits in lieu of salary under section 17(3)", profits_in_lieu),
        row("1d", "Total", total_current),
        row("1e", "Reported total amount of salary received from other employer(s)",
            previous_reported),
        row("2", "Less: allowances to the extent exempt under section 10", current_exempt),
        row("3", "Total amount of salary received from current employer [1(d) - 2]",
            salary_after_exemptions),
        row("4a", "Standard deduction under section 16(ia)", section_16["standard_deduction"]),
        row("4c", "Tax on employment under section 16(iii)", section_16["professional_tax"]),
        row("5", "Total amount of deductions under section 16", total_16),
        row("6", "Income chargeable under the head \"Salaries\" [3 + 1(e) - 5]", chargeable),
        row("9", "Gross total income", chargeable),
        row("11", "Aggregate of deductible amount under Chapter VI-A", via_total),
        row("12", "Total taxable income [9 - 11]", taxable),
        row("13", "Tax on total income", _d(computation.tax_before_rebate)),
        row("14", "Rebate under section 87A", _d(computation.rebate)),
        row("15", "Surcharge", _d(computation.surcharge)),
        row("16", "Health and education cess", _d(computation.cess)),
        row("17", "Tax payable [13 - 14 + 15 + 16]", tax_payable),
        row("18", "Less: relief under section 89", ZERO),
        row("19", "Net tax payable [17 - 18]", tax_payable),
    ]
    notes = list(computation.notes)
    for code, label in other_labels.items():
        notes.append(f"Included in salary: {label} ({_money(other[code])}).")
    notes.append(
        "Relief under section 89 for arrears is not computed here; it is claimed by the "
        "employee with Form 10E."
    )
    return {
        "regime": computation.regime,
        "lines": lines,
        "chapter_via": chapter_via,
        "hra": (
            {
                "exemption": str(_money(_d(computation.hra.exemption))),
                "explanation": computation.hra.explain(),
            }
            if computation.hra
            else None
        ),
        "tds": {
            "deducted_by_this_employer": str(_money(pay.tds_deducted)),
            "deducted_by_previous_employer": str(_money(inputs.previous_tds)),
            "total_deducted": str(_money(deducted)),
            "tax_payable": str(_money(tax_payable)),
            "balance": str(_money(balance)),
            "balance_note": (
                f"{_money(balance)} more tax is payable by the employee on filing."
                if balance > ZERO
                else f"{_money(-balance)} was deducted beyond the year's tax; it is "
                "refunded on filing."
                if balance < ZERO
                else "The tax deducted matches the tax payable."
            ),
        },
        "notes": notes,
    }


# ── Gathering ───────────────────────────────────────────────────────────────


def _assessment_year(financial_year: str) -> str:
    start = int(financial_year.split("-")[0])
    return f"{start + 1}-{str(start + 2)[-2:]}"


async def _closed_slips(
    session: AsyncSession, user: User, employee_id: uuid.UUID
) -> list[tuple[Payslip, PayrollRun]]:
    return list(
        (
            await session.execute(
                tenant_scoped(
                    select(Payslip, PayrollRun)
                    .join(PayrollRun, Payslip.run_id == PayrollRun.id)
                    .where(
                        Payslip.employee_id == employee_id,
                        PayrollRun.status.in_(_CLOSED),
                    )
                    .order_by(PayrollRun.period_year, PayrollRun.period_month),
                    Payslip,
                    user,
                )
            )
        ).all()
    )


async def _tds_rules_at(
    session: AsyncSession, user: User, on: date
) -> PayrollRuleSet | None:
    return await session.scalar(
        tenant_scoped(
            select(PayrollRuleSet)
            .where(
                PayrollRuleSet.rule_type == "tds",
                PayrollRuleSet.effective_from <= on,
                or_(PayrollRuleSet.effective_to.is_(None), PayrollRuleSet.effective_to >= on),
            )
            .order_by(PayrollRuleSet.effective_from.desc()),
            PayrollRuleSet,
            user,
        )
    )


def _fy_of(run: PayrollRun) -> str:
    """The financial-year label a closed run's TDS was worked in, April start
    unless its working says otherwise."""
    start_year = run.period_year if run.period_month >= 4 else run.period_year - 1
    return f"{start_year}-{str(start_year + 1)[-2:]}"


async def list_form16_years(
    session: AsyncSession, user: User, employee_id: uuid.UUID
) -> list[dict[str, Any]]:
    """Every financial year with approved payroll for this person, newest first,
    each with whether Part B can be produced and, if not, why."""
    rows = await _closed_slips(session, user, employee_id)
    years: dict[str, None] = {}
    for payslip, run in rows:
        label = (payslip.tds_working or {}).get("financial_year") or _fy_of(run)
        years[label] = None
    out = []
    for label in sorted(years, reverse=True):
        try:
            statement = await form16_statement(session, user, employee_id, label)
            out.append(
                {
                    "financial_year": label,
                    "assessment_year": statement["assessment_year"],
                    "available": True,
                    "reason": None,
                    "taxable_income": next(
                        line["amount"] for line in statement["lines"] if line["key"] == "12"
                    ),
                    "tax_payable": statement["tds"]["tax_payable"],
                    "tds_deducted": statement["tds"]["deducted_by_this_employer"],
                }
            )
        except Form16UnavailableError as exc:
            out.append(
                {
                    "financial_year": label,
                    "assessment_year": _assessment_year(label),
                    "available": False,
                    "reason": str(exc),
                    "taxable_income": None,
                    "tax_payable": None,
                    "tds_deducted": None,
                }
            )
    return out


async def form16_statement(
    session: AsyncSession, user: User, employee_id: uuid.UUID, financial_year: str
) -> dict[str, Any]:
    """Part B for one person and one financial year, or `Form16UnavailableError`."""
    from app.services.attendance.service import local_today
    from app.services.tax import service as tax_service

    try:
        int(financial_year.split("-")[0])
    except ValueError as exc:
        raise Form16UnavailableError(f"'{financial_year}' is not a financial year.") from exc

    fy_start, fy_end = tax_service.financial_year_bounds(financial_year)
    rule_set = await _tds_rules_at(session, user, fy_end)
    if rule_set is None or not rule_set.is_approved:
        raise Form16UnavailableError(
            f"No approved income-tax rule set was in force at the end of {financial_year}, "
            "so the year's tax cannot be computed."
        )
    start_month = int(rule_set.rules.get("financial_year_start_month", 4))
    if start_month != 4:
        fy_start, fy_end = tax_service.financial_year_bounds(financial_year, start_month)

    today = await local_today(session, user)
    if today <= fy_end:
        raise Form16UnavailableError(
            f"Form 16 for {financial_year} is issued after the financial year ends on "
            f"{fy_end:%d %b %Y}. Until then your payslips carry the projected tax."
        )

    rows = [
        (payslip, run)
        for payslip, run in await _closed_slips(session, user, employee_id)
        if fy_start <= run.effective_date <= fy_end
    ]
    if not rows:
        raise Form16UnavailableError(f"There is no approved payroll for {financial_year}.")

    employee = await session.scalar(
        tenant_scoped(select(Employee).where(Employee.id == employee_id), Employee, user)
    )
    if employee is None:
        raise Form16UnavailableError("Employee not found.")
    latest_run = rows[-1][1]
    entity = await session.scalar(
        tenant_scoped(
            select(LegalEntity).where(LegalEntity.id == latest_run.legal_entity_id),
            LegalEntity,
            user,
        )
    )
    entities = {run.legal_entity_id for _, run in rows}

    pay = aggregate_year_pay(
        [
            SlipFacts(
                period_year=run.period_year,
                period_month=run.period_month,
                gross_earnings=_d(payslip.gross_earnings),
                pf_wage_base=_d(payslip.pf_wage_base),
                professional_tax=_d(payslip.professional_tax),
                tds=_d(payslip.tds),
                line_items=list(payslip.line_items or []),
                input_lines=list(payslip.input_lines or []),
                tds_working=payslip.tds_working,
            )
            for payslip, run in rows
        ]
    )

    # The same basis the year's payroll used: declared amounts while the proof
    # window was open (or never set), proved and accepted ones after it closed.
    window = await tax_service.window_for(session, user, financial_year, WindowType.PROOF)
    use_declared = window is None or fy_end <= window.closes_at
    base = await tax_service.build_projection_input(
        session, user, employee_id, financial_year, use_declared_when_unproven=use_declared
    )
    inputs = year_projection_input(base, pay)
    try:
        computation = project(inputs, rule_set.rules)
        statement = part_b(pay=pay, inputs=inputs, computation=computation)
    except TaxRuleError as exc:
        raise Form16UnavailableError(str(exc)) from exc

    notes = statement["notes"]
    notes.insert(
        0,
        "Investments are counted as "
        + (
            "declared: the proof window was not closed for the year."
            if use_declared
            else "proved and accepted after the proof window closed."
        ),
    )
    if len(entities) > 1:
        notes.append(
            "Salary from more than one company in the group is included; each company "
            "issues its own Form 16 for its part of the year."
        )
    if not (employee.pan or "").strip():
        notes.append("There is no PAN on the employee record. Form 16 requires one.")
    if entity is not None and not (entity.tan or "").strip():
        notes.append("The employer's TAN is not on record.")

    first_y, first_m = pay.first_period
    last_y, last_m = pay.last_period
    return {
        "financial_year": financial_year,
        "assessment_year": _assessment_year(financial_year),
        "employer": {
            "name": entity.name if entity else None,
            "address": entity.registered_address if entity else None,
            "pan": entity.pan if entity else None,
            "tan": entity.tan if entity else None,
        },
        "employee": {
            "name": employee.full_name,
            "code": employee.employee_code,
            "pan": employee.pan,
            "designation": employee.designation,
        },
        "period_from": date(first_y, first_m, 1).isoformat(),
        "period_to": min(fy_end, _month_end(last_y, last_m)).isoformat(),
        "months": pay.months,
        **statement,
    }


def _month_end(year: int, month: int) -> date:
    import calendar

    return date(year, month, calendar.monthrange(year, month)[1])


