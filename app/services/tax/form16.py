"""Form 16 Part B: the annual statement of salary paid and tax deducted.

═══════════════════════════════════════════════════════════════════════════════
WHAT THIS IS, AND WHAT IT IS NOT
═══════════════════════════════════════════════════════════════════════════════

Form 16 has two parts. **Part A** — the TDS deducted and deposited quarter by
quarter, certified against the employer's TAN — is generated by the Income Tax
department's TRACES portal from the TDS returns the employer filed. AskMira
does not have it and does not imitate it.

**Part B** is the employer's own computation of the employee's salary income
for the year. This module builds it from what payroll actually did:

- salary, perquisites and one-off pay from the **approved payslips** of the
  financial year, month by month — never from today's salary record;
- exemptions, deductions and the tax itself from the same `project()` the
  monthly TDS used, against the income-tax rule set in force at the year's
  end, with the employee's regime election and their accepted (or, where the
  proof window never closed, declared) investments — the same basis payroll
  used;
- the tax deducted as the sum of TDS on those payslips.

It is issued only after the financial year has ended, because before then it
would be a projection presented as a certificate. The PDF says it is an
unsigned copy: the employer's authorised signatory signs the one they issue.
═══════════════════════════════════════════════════════════════════════════════
"""

